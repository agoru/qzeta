"""leanrefs: the label map of a hand-written Lean library, read from its docstrings.

A declaration whose docstring starts with tags `[lem:x]` (and optionally an item `(k)` after the tags) states the
result `lem:x` (its item `(k)`). A library may prefix the tag with its paper, `[paper:lem:x]`,
`[paper:thm:y]`; the map is keyed by the label as the LaTeX writes it (`lem:x`), and `paper=` keeps the tags of
one paper (and the unprefixed ones). A tag may be followed by its own items, `[paper:lem:cost] (a) [paper:thm:effective]
(2)`: (a) is the item of lem:cost and (2) that of thm:effective; tags with nothing between them share the items that
follow them (`[lem:a] [lem:b] (2)`: (2) of both), as before. An item is `(k)`, `(2a)` or a word `(sums)`; a further
marker after it (`(d) (base)`) or a phrase (`(the claim, stop)`) is not an item. A marker `(step ...)` makes the
declaration a proof step (`[paper:lem:x] (2) (step gap)`): it formalizes a line of the proof, not the statement, so
label_map leaves it out (the match check does not try it) and label_map(..., steps=True) lists it. The map gives, per label, the
declarations with their full names (namespaces resolved) and items. qpp2lean uses it for the match check: the
hand-written declaration must prove the statement that the LaTeX states.

Usage: python3 -m qpp.leanrefs DIR [--paper P] [--label L]
"""
import re
import sys
from pathlib import Path

DECL = re.compile(r"(?:(?:private|protected|noncomputable|@\[[^\]]*\])\s+)*(theorem|lemma|def|abbrev|structure|instance|inductive|class)\s+"
                  r"([^\s(:{\[]+)")
KINDS = "lem|thm|prop|cor|def|ex|op|rem|con|fact|conj|prob|eq|tab|app|alg"
# [lem:x], or with the paper: [paper:lem:x]; the label is the part from the kind on
TAG = re.compile(r"\[(?:([a-z][a-z0-9]*):)?((?:" + KINDS + r"):[A-Za-z0-9_\-:]+)\]")
ITEM = re.compile(r"\(([A-Za-z0-9]+(?: [0-9]+)?)\)")  # (2), (sums), (core 1)
MARK = re.compile(r"\([^()\n]*\)")


STEP = re.compile(r"\(step\b[^()\n]*\)")


def read_tags_full(head):
    """the tags at the start of a docstring with their items and whether they mark a proof step: [(paper or None,
    label, item or None, step)]. A marker (step ...) after a tag, `[paper:lem:x] (2) (step gap)` or
    `[paper:con:coprime] (step the claim)`, says that the declaration formalizes a line of the proof, not the
    statement (or the item): the match check ignores it and the status page counts it apart."""
    out, run = [], []
    while True:
        t = TAG.match(head)
        if not t:
            break
        run.append((t.group(1), t.group(2)))
        head = head[t.end():].lstrip()
        item, step = None, False
        marks = 0
        while True:
            mk = MARK.match(head)
            if not mk:
                break
            if STEP.fullmatch(mk.group(0)):
                step = True
            elif marks == 0:
                im = ITEM.fullmatch(mk.group(0))
                item = f"({im.group(1)})" if im else None
            marks += 1
            head = head[mk.end():].lstrip()
        if marks:
            out += [(p, lab, item, step) for p, lab in run]
            run = []
    out += [(p, lab, None, False) for p, lab in run]
    return out


def read_tags(head):
    """the tags at the start of a docstring with their items: [(paper or None, label, item or None)], proof steps
    left out (read_tags_full)"""
    return [(p, lab, item) for p, lab, item, step in read_tags_full(head) if not step]


def _declarations(root):
    """every declaration with a docstring in the .lean files under root: (full name, kind, file, docstring, text of
    the file, end of the declaration's name), namespaces resolved"""
    for f in sorted(Path(root).rglob("*.lean")):
        if ".lake" in f.parts:
            continue
        text = f.read_text(encoding="utf-8")
        ns = []
        for m in re.finditer(r"/--(.*?)-/\s*|^(namespace|end|section)\s+([^\s]*)\s*$|^(namespace|section|end)\s*$",
                             text, re.S | re.M):
            if m.group(2) == "namespace":
                ns.append(("ns", m.group(3)))
                continue
            if m.group(2) == "section" or m.group(4) == "section":
                ns.append(("sec", m.group(3) or ""))
                continue
            if m.group(2) == "end" or m.group(4) == "end":
                if ns:
                    ns.pop()
                continue
            d = DECL.match(text, m.end())
            if not d:
                continue
            prefix = ".".join(n for k, n in ns if k == "ns" and n)
            full = (prefix + "." if prefix else "") + d.group(2)
            yield full, d.group(1), str(f.relative_to(root)), m.group(1), text, d.end()


KERNEL_HEADER = "generated by qpp/kernel.py"


def label_map(root, paper=None, steps=False, kernel=True):
    """{label: [(full name, item or None, kind, file)]}; with paper, the tags of that paper and the unprefixed ones;
    the declarations of proof steps (a marker (step ...)) are left out, or, with steps=True, the only ones kept;
    with kernel=False, the declarations generated by the kernel backend (qpp/kernel.py) are left out: their
    statement is the paper's row itself, so the match check has nothing to match"""
    out = {}
    for full, kind, file, doc, text, _end in _declarations(root):
        if not kernel and KERNEL_HEADER in text[:400]:
            continue
        tags = [(lab, item) for p, lab, item, step in read_tags_full(doc.strip())
                if (paper is None or p in (None, paper)) and step == steps]
        for lab, item in tags:
            entry = (full, item, kind, file)
            if entry not in out.get(lab, []):
                out.setdefault(lab, []).append(entry)
    return out


def kernel_items(root):
    """the (label, item) of the declarations generated by the kernel backend (qpp/kernel.py)"""
    full, hand = label_map(root), label_map(root, kernel=False)
    return {(lab, item) for lab, es in full.items() for _f, item, _k, _file in es if _f not in {e[0] for e in hand.get(lab, [])}}


# a cited fact stated once: `structure X : Prop where`, with no parameters (a parameterized one, BandsGap q n ..., is
# a hypothesis about particular data, which the statement itself has to state)
FACT0 = re.compile(r"\s*:\s*Prop\s+where\b")
SIGNATURE_END = re.compile(r":=|\bwhere\b|^\s*\|", re.M)


def registers_fact(doc):
    """the docstring registers a cited fact: a tag at its start of kind fact (`[paper:fact:bands]`) or the tag of the
    paper's table of facts (`[paper:tab:facts]`)"""
    return any(lab.startswith("fact:") or lab == "tab:facts" for _p, lab, _i, _s in read_tags_full(doc.strip()))


def unregistered_facts(root):
    """[(full name, file)]: the structures `structure X : Prop where` with no parameters whose docstring does not
    register them as cited facts (registers_fact). The match check does not take them as hypotheses, so a declaration
    that needs one is not matched; they are reported"""
    return [(full, f) for full, kind, f, doc, text, end in _declarations(root)
            if kind == "structure" and FACT0.match(text, end) and not registers_fact(doc)]


def cited_premises(root):
    """{full name of a declaration: [the cited facts it takes]}: the structures `structure X : Prop where` with no
    parameters (the Lean side of a cited theorem, never an axiom), registered as cited facts by a fact: or tab:facts
    tag (registers_fact), that the declaration's signature names. The match check takes them as hypotheses,
    `example (hc_1 : X) : <statement>`: the statement of the paper follows from the declaration given the cited
    theorem, which is what the paper claims. Any other proposition taken as a premise is no hypothesis of the
    example, so it cannot make a match vacuous."""
    decls = list(_declarations(root))
    facts = {}
    for full, kind, _file, doc, text, end in decls:
        if kind == "structure" and FACT0.match(text, end) and registers_fact(doc):
            facts.setdefault(full.rsplit(".", 1)[-1], full)
    out = {}
    if not facts:
        return out
    word = re.compile(r"(?<![\w.'])(?:[\w']+\.)*(" + "|".join(map(re.escape, facts)) + r")(?![\w'])")
    for full, kind, _file, _doc, text, end in decls:
        if kind not in ("theorem", "lemma"):
            continue
        stop = SIGNATURE_END.search(text, end)
        sig = text[end:stop.start() if stop else len(text)]
        names = sorted({facts[m.group(1)] for m in word.finditer(sig)})
        if names:
            out[full] = names
    return out


def main(argv):
    m = label_map(argv[0], argv[argv.index("--paper") + 1] if "--paper" in argv else None)
    if "--label" in argv:
        lab = argv[argv.index("--label") + 1]
        for x in m.get(lab, []):
            print(*x)
        return 0
    st = label_map(argv[0], argv[argv.index("--paper") + 1] if "--paper" in argv else None, steps=True)
    print(f"{len(m)} labels, {sum(len(v) for v in m.values())} declarations"
          + (f"; proof steps: {sum(len(v) for v in st.values())} declarations for {len(st)} labels" if st else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
