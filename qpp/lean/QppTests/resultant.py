"""Writes QppTests/Resultant.lean: Bezout identities of resultants, U A + V B = Res_y(A, B), as identities of counts.

The polynomials A are losses of a set of examples, and B = dA/dy. The resultant and its cofactors are computed by
qpp.qpoly.resultant (eq:resbezout),
and the identity is checked here in exact arithmetic before it is written. Over the counts an identity with signs
is written balanced: with P = P+ - P- for each polynomial,

    U+ A+ + U- A- + V+ B+ + V- B- + R- = U+ A- + U- A+ + V+ B- + V- B+ + R+,

an empty part being absent. A polynomial identity with integer coefficients holds if and only if its balanced form
holds for all counts x, y, since a polynomial that vanishes on all counts is zero.

Usage (from the root of the repository): python3 qpp/lean/QppTests/resultant.py
"""
import sys
import time
from fractions import Fraction
from math import lcm
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from qpp.qpoly import Poly, resultant  # noqa: E402

OUT = Path(__file__).resolve().parent / "Resultant.lean"
NAMES = ("x", "y")


def cases():
    x, y = Poly.var(0, 2), Poly.var(1, 2)
    f = (y * y - x ** 3) ** 2 - x ** 5 * y
    return [
        ("member", "the member f = (y^2-x^3)^2-x^5y of the row ((y^2-x^3)^2-x^5y)^2+x^14+y^14", f),
        ("product", "the product f (y - x) + x^9 of that member with a line", f * (y - x) + x ** 9),
        ("loss", "the loss K = ((y^2-x^3)^2-x^5y)^2+x^14+y^14 of that row", f * f + x ** 14 + y ** 14),
    ]


def integral(polys):
    """the polynomials times the least common multiple of all their denominators"""
    den = 1
    for p in polys:
        for c in p.t.values():
            den = lcm(den, Fraction(c).denominator)
    return [Poly(p.nv, {e: c * den for e, c in p.t.items()}) for p in polys]


def monomial(e, c):
    factors = [] if c == 1 and any(e) else [str(c)]
    for name, k in zip(NAMES, e):
        if k == 1:
            factors.append(name)
        elif k > 1:
            factors.append(f"{name} ^ {k}")
    return " * ".join(factors)


def parts(p):
    """the positive part and the negative part of p, as lists of monomials with positive coefficients"""
    terms = sorted(p.t.items(), reverse=True)
    pos = [monomial(e, int(c)) for e, c in terms if c > 0]
    neg = [monomial(e, int(-c)) for e, c in terms if c < 0]
    return pos, neg


def wrap(terms, indent, width=116):
    lines, line = [], indent
    for i, t in enumerate(terms):
        piece = t + (" + " if i < len(terms) - 1 else "")
        if len(line) + len(piece) > width and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += piece
    lines.append(line.rstrip())
    return "\n".join(lines)


def side(products, extra, indent):
    """a sum of products of parts, the absent ones left out"""
    summands = []
    for a, b in products:
        if a and b:
            summands.append((a, b))
    out = []
    for a, b in summands:
        out.append("(" + wrap(a, indent + " ").lstrip() + ") *\n" + indent + "(" + wrap(b, indent + " ").lstrip() + ")")
    if extra:
        out.append("(" + wrap(extra, indent + " ").lstrip() + ")")
    return (" +\n" + indent).join(out)


def theorem(name, doc, A):
    B = A.diff(1)
    t0 = time.time()
    R, U, V = resultant(A, B, 1, cofactors=True)
    assert U * A + V * B == R, name
    A, B, R, U, V = integral([A, B, R, U, V])
    assert U * A + V * B == R, name
    (Ap, An), (Bp, Bn), (Rp, Rn), (Up, Un), (Vp, Vn) = map(parts, (A, B, R, U, V))
    lhs = side([(Up, Ap), (Un, An), (Vp, Bp), (Vn, Bn)], Rn, "    ")
    rhs = side([(Up, An), (Un, Ap), (Vp, Bn), (Vn, Bp)], Rp, "    ")
    terms = sum(len(p.t) for p in (A, B, R, U, V))
    bits = max(abs(int(c)).bit_length() for p in (A, B, R, U, V) for c in p.t.values())
    stats = (f"deg_y A = {A.deg(1)}; {len(U.t)} + {len(V.t)} terms in U, V and {len(R.t)} in R; "
             f"coefficients up to {bits} bits")
    print(f"{name}: {stats} ({time.time() - t0:.1f} s in Python)")
    return (f"/-- The Bezout identity of the resultant of A and dA/dy in y, for A {doc}: {stats}. -/\n"
            f"theorem res_{name} (x y : Count) :\n    {lhs} =\n    {rhs} := by\n  qeq\n")


def main():
    body = "\n".join(theorem(*c) for c in cases())
    OUT.write_text(
        "module\n\npublic import QppKernel\n\n"
        "/-!\n# Resultant identities, checked by `qeq`\n\n"
        "Generated by `QppTests/resultant.py` from exact resultants (`qpp.qpoly.resultant`): the Bezout "
        "identity\n`U A + V B = Res_y(A, B)` with `B = dA/dy`, balanced over the counts. Do not edit.\n-/\n\n"
        "public section\n\nnamespace Qpp.Tests\n\n" + body + "\nend Qpp.Tests\n\nend\n", encoding="ascii")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(OUT.read_text().splitlines())} lines, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
